def main():
    print("=" * 76)
    print("文章配方体检器：Adrian Punk 五技巧 → 官方八要素规则映射（确定性，无 API）")
    print("=" * 76)
    print("""
技巧 → 规则映射（文章第三部分 ↔ 已入库 [[图像提示八要素]]）：
  技巧1 修改项与保留项分开写   → R6 将修改与约束分开   （同源：[[修改与约束分离]] 三段式）
  技巧2 给多张参考图明确分工   → R7 为参考资料分配角色
  技巧3 把文字当成固定内容交付 → R5 提供准确的文本（引号逐字+位置字体+负向排除）
  技巧4 用可见细节替换'高级感' → R3 描述可见细节
  技巧5 给创意设置一个锚点     → R9 单一视觉锚点（ex5 新增，仅创作类场景计分）""")
    results = []
    for title, ctx_set, prompt in CASES:
        score, lines = audit2(prompt, ctx_set)
        results.append((title, score))
        print(f"\n【{title}】 ctx={sorted(ctx_set)}  得分: {score}/100")
        for l in lines:
            print(l)
    print("\n" + "=" * 76)
    print("配对单调性验证（同一场景 口语版 → 文章配方版）：")
    pairs = [(0, 1), (2, 3), (4, 5), (6, 7)]
    all_mono = True
    for a, b in pairs:
        mono = results[b][1] > results[a][1]
        all_mono &= mono
        print(f"  {results[a][1]:>3} → {results[b][1]:>3}  单调={mono}  "
              f"{results[a][0].split('·')[0]}")
    print(f"\n结论：4 组配对全部单调提升 = {all_mono}。")
    print("文章五技巧不是新发明，而是官方八要素在电商实战场景的逐条实例化；")
    print("9 个场景配方 = 同一套规则在不同翻车点上的排列组合。")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
